#!/usr/bin/env python3
"""Generates the app's text tables from the translations in i18n/, or checks them.

Every text the app shows is written once per language, keyed by id, in i18n/<lang>.json: an object of
tables, each an object of id -> text. Keys that start with "//" are notes for translators, and are skipped.
The first language of LANGUAGES is the model (Spanish, i18n/spa.json): its tables, its ids and their order
are the ones every language defines.

An app can load string resources only in the watch's language, so the texts ship as JSON data instead: for
each language, one array per table, in the model's order (resources/i18n/<lang>.xml). The code finds a text
by its key, a constant in source/I18nKeys.mc: the table's number times TABLE_KEYS plus the text's index in
the table. The first table, "glance", is the only one marked scope="glance", the only one the glance can
load. A lookup loads its whole table, so a long text (a prayer) gets a table of its own: only it is loaded.

Usage:
  python3 scripts/gen-i18n.py          writes resources/i18n/<lang>.xml and source/I18nKeys.mc
  python3 scripts/gen-i18n.py --check  writes nothing; exits 1 when a language is incomplete, or when a
                                       generated file differs from what the translations generate

A language is incomplete when it leaves out a table or an id, leaves a text empty, has an id the model does
not, or adds a $N$ placeholder the model does not have. Leaving a placeholder out is allowed.

The app reads only Spanish so far. A new language adds its file to i18n/ and its code to LANGUAGES, and
source/I18n.mc's resolve picks it for its watches.
"""
import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "i18n"
RESOURCES = ROOT / "resources" / "i18n"
KEYS_FILE = ROOT / "source" / "I18nKeys.mc"
# The languages, in the order of I18n.Language. The first is the model.
LANGUAGES = ["spa"]
MODEL = LANGUAGES[0]
GLANCE_TABLE = "glance"
# Texts a table may hold: a key's index in its table is key % TABLE_KEYS.
TABLE_KEYS = 256
PLACEHOLDER = re.compile(r"\$\d+\$")
HEADER = "Generated by scripts/gen-i18n.py from {sources}."
DO_NOT_EDIT = "Do not edit: change {change} and run python3 scripts/gen-i18n.py."


def is_note(key):
    return key.startswith("//")


def texts_of(table):
    """The table's (id, text) pairs, notes left out."""
    return [(key, text) for key, text in table.items() if not is_note(key)]


def read_sources():
    """{language: {table: [(id, text)]}}, or exits with the reason when a file cannot be read."""
    found = sorted(path.stem for path in SOURCES.glob("*.json"))
    if found != sorted(LANGUAGES):
        sys.exit(f"i18n/ holds {found}; expected one file per language of {LANGUAGES} (see LANGUAGES)")
    sources = {}
    for language in LANGUAGES:
        path = SOURCES / f"{language}.json"
        try:
            document = json.loads(path.read_text(encoding="utf-8"))
        except ValueError as error:
            sys.exit(f"i18n/{path.name}: not valid JSON: {error}")
        if not isinstance(document, dict):
            sys.exit(f"i18n/{path.name}: expected an object of tables")
        tables = {}
        for name, table in document.items():
            if is_note(name):
                continue
            if not isinstance(table, dict):
                sys.exit(f"i18n/{path.name}: table {name} is not an object of id -> text")
            tables[name] = texts_of(table)
        sources[language] = tables
    return sources


def problems_in(sources):
    """Why a language is incomplete, one line per problem."""
    model = sources[MODEL]
    model_file = f"i18n/{MODEL}.json"
    problems = []
    names = list(model)
    if not names or names[0] != GLANCE_TABLE:
        problems.append(f"{model_file}: the first table must be \"{GLANCE_TABLE}\", the glance's")
    for name, texts in model.items():
        if len(texts) > TABLE_KEYS:
            problems.append(f"{model_file}: table {name} holds {len(texts)} texts, more than {TABLE_KEYS}")
        if not texts:
            problems.append(f"{model_file}: table {name} holds no text")
    for language, tables in sources.items():
        where = f"i18n/{language}.json"
        for name in tables:
            if name not in model:
                problems.append(f"{where}: table {name} is not in {model_file}")
        for name, model_texts in model.items():
            if name not in tables:
                problems.append(f"{where}: leaves out table {name}")
                continue
            texts = dict(tables[name])
            model_ids = [key for key, _ in model_texts]
            for key in texts:
                if key not in model_ids:
                    problems.append(f"{where}: {name}.{key} is not in {model_file}")
            for key, model_text in model_texts:
                text = texts.get(key)
                if text is None:
                    problems.append(f"{where}: leaves out {name}.{key}")
                elif not isinstance(text, str) or not text.strip():
                    problems.append(f"{where}: {name}.{key} is empty or not a text")
                else:
                    added = sorted(set(PLACEHOLDER.findall(text)) - set(PLACEHOLDER.findall(model_text)))
                    if added:
                        problems.append(f"{where}: {name}.{key} adds {', '.join(added)}, which the model "
                                        f"\"{model_text}\" does not have")
    return problems


def resource_id(table, language):
    """"titles", "spa" -> "TitlesSpa"."""
    return table[0].upper() + table[1:] + language.capitalize()


def resource_file(sources, language):
    """resources/i18n/<language>.xml: the language's tables as JSON arrays, in the model's order."""
    model = sources[MODEL]
    texts = {name: dict(tables) for name, tables in sources[language].items()}
    lines = [
        "<jsonDataResources>",
        f"    <!-- {HEADER.format(sources=f'i18n/{language}.json')} {DO_NOT_EDIT.format(change='that file')} -->",
    ]
    for name, model_texts in model.items():
        scope = ' scope="glance"' if name == GLANCE_TABLE else ""
        entries = [escape(json.dumps(texts[name][key], ensure_ascii=False)) for key, _ in model_texts]
        lines.append(f'    <jsonData id="{resource_id(name, language)}"{scope}>[')
        lines.append(",\n".join("        " + entry for entry in entries))
        lines.append("    ]</jsonData>")
    lines.append("</jsonDataResources>")
    return "\n".join(lines) + "\n"


def enum_lines(model, names, first_table):
    lines = []
    for number, name in enumerate(names, first_table):
        lines.append(f"    // Table {number}: \"{name}\" in i18n/<lang>.json.")
        lines.append("    enum {")
        keys = [f"        {key} = {number * TABLE_KEYS + index}" for index, (key, _) in enumerate(model[name])]
        lines.append(",\n".join(keys))
        lines.append("    }")
        lines.append("")
    return lines


def keys_file(sources):
    """source/I18nKeys.mc: the languages, every text's key and the resource of every table."""
    model = sources[MODEL]
    names = list(model)
    sources_named = ", ".join(f"i18n/{language}.json" for language in LANGUAGES)
    glance_ids = ", ".join(f"Rez.JsonData.{resource_id(GLANCE_TABLE, language)}" for language in LANGUAGES)
    all_ids = ",\n".join(f"            Rez.JsonData.{resource_id(name, language)}"
                         for language in LANGUAGES for name in names)
    lines = [
        "import Toybox.Lang;",
        "",
        "// " + HEADER.format(sources=sources_named),
        "// " + DO_NOT_EDIT.format(change="those files"),
        "//",
        "// A text's key is its table's number times TABLE_KEYS plus its index in the table, so a lookup knows",
        "// which table to load (I18n.mc). Only the glance table's keys and resources are glance-annotated: the",
        "// glance can load no other table.",
        "(:glance)",
        "module I18n {",
        "    // The languages, in the order of the tables in tableId.",
        "    enum Language {",
        ",\n".join(f"        {language.upper()}" for language in LANGUAGES),
        "    }",
        "",
        f"    const LANGUAGE_COUNT = {len(LANGUAGES)};",
        f"    const TABLE_KEYS = {TABLE_KEYS};",
        "",
    ]
    lines += enum_lines(model, names[:1], 0)
    lines += [
        "    // The glance table of a language.",
        "    function glanceTable(language as Language) as ResourceId {",
        f"        var ids = [{glance_ids}] as Array<ResourceId>;",
        "        return ids[language as Number];",
        "    }",
        "}",
        "",
        "// The other tables, which only the full-screen widget loads.",
        "module I18n {",
        f"    const TABLE_COUNT = {len(names)};",
        "",
    ]
    lines += enum_lines(model, names[1:], 1)
    lines += [
        "    // The resource of a table (0..TABLE_COUNT - 1) in a language: every language's tables in turn.",
        "    function tableId(table as Number, language as Language) as ResourceId {",
        "        var ids = [",
        all_ids,
        "        ] as Array<ResourceId>;",
        "        return ids[(language as Number) * TABLE_COUNT + table];",
        "    }",
        "}",
    ]
    return "\n".join(lines) + "\n"


def generated(sources):
    """{path: content} of every generated file."""
    files = {RESOURCES / f"{language}.xml": resource_file(sources, language) for language in LANGUAGES}
    files[KEYS_FILE] = keys_file(sources)
    return files


def main(argv):
    check = argv[1:] == ["--check"]
    if argv[1:] and not check:
        sys.exit(__doc__)
    sources = read_sources()
    problems = problems_in(sources)
    if problems:
        print("Translations FAILED:")
        for problem in problems:
            print("  " + problem)
        return 1
    files = generated(sources)
    model = sources[MODEL]
    summary = (f"{len(LANGUAGES)} language{'s' if len(LANGUAGES) != 1 else ''} x {len(model)} tables, "
               f"{sum(len(t) for t in model.values())} texts each")
    if check:
        stale = [path for path, content in files.items()
                 if not path.exists() or path.read_text(encoding="utf-8") != content]
        stale += [path for path in sorted(RESOURCES.glob("*")) if path not in files]
        if stale:
            print("Translations FAILED: generated files differ from i18n/ (run python3 scripts/gen-i18n.py):")
            for path in stale:
                print("  " + str(path.relative_to(ROOT)))
            return 1
        print(f"Translations OK: {summary}; generated files up to date.")
        return 0
    RESOURCES.mkdir(parents=True, exist_ok=True)
    for path in sorted(RESOURCES.glob("*")):
        if path not in files:
            path.unlink()
    for path, content in files.items():
        path.write_text(content, encoding="utf-8")
    print(f"Generated {', '.join(str(path.relative_to(ROOT)) for path in files)}: {summary}.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
